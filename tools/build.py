"""Compile editable Markdown into file:// compatible course data; no server required."""
import html
import argparse
import json
import re
import zipfile
from pathlib import Path
import markdown
from markdown.extensions import Extension
from markdown.inlinepatterns import InlineProcessor
from markdown.preprocessors import Preprocessor
import xml.etree.ElementTree as ET
from pygments.formatters import HtmlFormatter

ROOT = Path(__file__).resolve().parents[1]

class InlineMath(InlineProcessor):
    def handleMatch(self, match, data):
        element = ET.Element("span", {"class": "math-source"})
        from markdown.util import AtomicString
        element.text = AtomicString("$" + match.group(1) + "$")
        return element, match.start(0), match.end(0)

class DisplayMath(Preprocessor):
    def run(self, lines):
        result, buffer, in_code, in_math = [], [], False, False
        for line in lines:
            if line.strip().startswith("```"):
                in_code = not in_code
            if not in_code and line.strip() == "$$":
                if not in_math:
                    in_math = True
                    buffer = []
                else:
                    rendered = '<div class="math-block">$$\n' + html.escape("\n".join(buffer)) + '\n$$</div>'
                    result.extend(["", self.md.htmlStash.store(rendered), ""])
                    in_math = False
            elif in_math:
                buffer.append(line)
            else:
                result.append(line)
        if in_math:
            raise ValueError("Unclosed display math")
        return result

class MathExtension(Extension):
    def extendMarkdown(self, md):
        md.preprocessors.register(DisplayMath(md), "display_math", 27)
        md.inlinePatterns.register(InlineMath(r"(?<!\\)\$(?!\$)([^\n$]+?)(?<!\\)\$(?!\$)", md), "inline_math", 185)

def build(course_path):
    catalog = json.loads((course_path / "course.json").read_text(encoding="utf-8"))
    count = 0
    for lesson in catalog["lessons"]:
        source = (course_path / "chapters" / (lesson["id"] + ".md")).read_text(encoding="utf-8")
        source = re.sub(r"<!-- example:([a-zA-Z0-9_]+\.py) -->", lambda m: "```python\n" + (course_path / "examples" / m.group(1)).read_text(encoding="utf-8").rstrip() + "\n```", source)
        md = markdown.Markdown(extensions=["fenced_code", "tables", "toc", "codehilite", MathExtension()], extension_configs={"codehilite": {"guess_lang": False}, "toc": {"permalink": False}})
        lesson["html"] = md.convert(source)
        languages = iter(re.findall(r"^```([^\s`]*)", source, re.M)[::2])
        lesson["html"] = re.sub(r'<div class="codehilite">', lambda _: '<div class="codehilite" data-language="' + html.escape(next(languages, "code"), quote=True) + '">', lesson["html"])
        lesson["text"] = source
        lesson["toc"] = md.toc_tokens
        lesson["minutes"] = max(4, round(len(re.findall(r"[\u4e00-\u9fff]", source)) / 210 + len(re.findall(r"^", source, re.M)) / 22))
        count += len(source)
    (course_path / "assets").mkdir(parents=True, exist_ok=True)
    (course_path / "assets" / "course-data.js").write_text("/* Generated by tools/build.py. Edit chapters/*.md and course.json. */\nwindow.COURSE = " + json.dumps(catalog, ensure_ascii=False) + ";\n", encoding="utf-8")
    if catalog.get("slug") == "llm":
        with zipfile.ZipFile(course_path / "examples.zip", "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for example_path in sorted((course_path / "examples").iterdir()):
                if example_path.is_file() and example_path.suffix in {".py", ".md", ".txt"}:
                    info = zipfile.ZipInfo("examples/" + example_path.name, date_time=(2026, 10, 29, 0, 0, 0))
                    info.compress_type = zipfile.ZIP_DEFLATED
                    archive.writestr(info, example_path.read_bytes())
    style = HtmlFormatter(style="github-dark").get_style_defs(".codehilite")
    (ROOT / "assets" / "syntax.css").write_text(style, encoding="utf-8")
    print(f"Built {course_path.name}: {len(catalog['lessons'])} chapters / {count:,} source characters")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("subjects", nargs="*", help="Subject folders; default: all courses")
    args = parser.parse_args()
    names = args.subjects or [p.parent.name for p in sorted(ROOT.glob("*/course.json"))]
    for name in names:
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name):
            parser.error(f"Invalid subject folder: {name}")
        build(ROOT / name)
