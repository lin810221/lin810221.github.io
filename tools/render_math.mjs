/* Build-time KaTeX: reading a generated equation needs CSS/fonts, no math JS. */
import {readFile,writeFile,readdir} from 'node:fs/promises';
import katex from '../assets/vendor/katex/katex.mjs';
const root=new URL('../',import.meta.url);
const decode=s=>s.replace(/&(?:amp|lt|gt|quot|#x27);/g,x=>({'&amp;':'&','&lt;':'<','&gt;':'>','&quot;':'"','&#x27;':"'"}[x]));
export function renderHTMLMath(html,label='formula'){
  return html.replace(/<(span|div)([^>]* data-tex="([^"]*)"[^>]*)>([\s\S]*?)<\/\1><!--math-end-->/g,(_,tag,attrs,encoded)=>{
    const tex=decode(encoded),display=/data-display="true"/.test(attrs);
    try{
      const rendered=katex.renderToString(tex,{displayMode:display,throwOnError:true,trust:false,strict:'ignore',output:'htmlAndMathml'});
      return `<${tag}${attrs.replace(/ data-rendered="[^"]*"/g,'')} data-rendered="katex">${rendered}</${tag}><!--math-end-->`;
    }catch(error){throw new Error(`${label}: ${error.message}; TeX=${tex}`);}
  });
}
export async function renderMathCourses(names=[]){
  if(!names.length){for(const entry of await readdir(root,{withFileTypes:true})){if(!entry.isDirectory()||entry.name.startsWith('.'))continue;try{await readFile(new URL(`${entry.name}/course.json`,root));names.push(entry.name);}catch{}}}
  const reports=[];
  for(const name of names){
    if(!/^[a-z0-9][a-z0-9-]*$/.test(name))throw new Error('Invalid course folder');
    const path=new URL(`${name}/assets/course-data.js`,root),raw=await readFile(path,'utf8');
    const course=JSON.parse(raw.split('window.COURSE = ')[1].trim().replace(/;$/,''));let count=0;
    for(const lesson of course.lessons){
      count+=(lesson.html.match(/data-tex=/g)||[]).length;
      lesson.html=renderHTMLMath(lesson.html,`${name}/${lesson.id}`);
      if(lesson.summaryHTML)lesson.summaryHTML=renderHTMLMath(lesson.summaryHTML,`${name}/${lesson.id}/summary`);
    }
    course.mathRenderer={name:'KaTeX',version:katex.version,prerendered:true};
    await writeFile(path,'/* Generated by tools/build.py and render_math.mjs. */\nwindow.COURSE = '+JSON.stringify(course)+';\n','utf8');
    reports.push({course:name,equations:count,version:katex.version});
  }
  return reports;
}
